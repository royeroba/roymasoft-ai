#!/usr/bin/env node
/**
 * Projects the harness into a target repository, in each agent's native format.
 *
 * One source of truth (`behavior/`, `agents/`, `skills/`, `contracts/`) becomes five
 * agent-specific projections. Copies, never symlinks: symlinks need elevation or developer
 * mode on Windows, and they break in ZIP downloads.
 *
 * Usage:  node build/project.mjs [target-repo]     (defaults to cwd)
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HARNESS = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = resolve(process.argv[2] ?? process.cwd());

/** Where the harness detail files land inside the target repository. */
const VENDOR = '.roymasoft';

/** Idempotent block markers: everything outside them is the user's and is preserved. */
const BLOCK_START = '<!-- roymasoft-ai:start -->';
const BLOCK_END = '<!-- roymasoft-ai:end -->';

/**
 * Behaviour files that become individually addressable rules, with the description each
 * agent uses to decide when to attach them.
 */
const BEHAVIOR_RULES = {
	'evidence.md': 'Never assume. What may be claimed and the proof required. When to stop and ask.',
	'output.md': 'Response shape: lead with the action, no preamble, no recap, no closers.',
	'language.md': 'Conversation language vs. technical artifact language.',
	'routing.md': 'Ceremony ladder: ping-pong vs SDD, and when TDD applies.',
	'search.md': 'Search order: graph, grep, glob, read. Never bash to search.',
	'memory.md': 'What to persist, with which scope, and client isolation.',
	'code-style.md': 'SOLID, DRY, KISS, Clean Code. Docstrings on signatures, no comments.',
	'security.md': 'Secrets, destructive commands, untrusted content.',
	'verification.md': 'How the TDD mode is resolved and what counts as proof.',
};

const log = (msg) => console.log(`  ${msg}`);

function read(rel) {
	return readFileSync(join(HARNESS, rel), 'utf8');
}

function write(relTarget, content) {
	const abs = join(TARGET, relTarget);
	mkdirSync(dirname(abs), { recursive: true });
	writeFileSync(abs, content, 'utf8');
	log(`wrote ${relTarget}`);
}

function generatedHeader(regenCmd) {
	return [
		`<!-- Generated by roymasoft-ai. Do not edit directly.`,
		`     Edit the harness and re-run: ${regenCmd} -->`,
		'',
	].join('\n');
}

/**
 * Rewrites the core's lazy pointers so they resolve from the target repository root.
 * `behavior/evidence.md` -> `.roymasoft/behavior/evidence.md`
 */
function rewritePointers(text) {
	return text.replace(/(`)(behavior|contracts|agents|skills)\//g, `$1${VENDOR}/$2/`);
}

/** Copies a harness directory into the target's vendor folder. Skips silently if absent. */
function vendorDir(name) {
	const src = join(HARNESS, name);
	if (!existsSync(src)) return false;
	let count = 0;
	const walk = (dir) => {
		for (const entry of readdirSync(dir)) {
			const abs = join(dir, entry);
			if (statSync(abs).isDirectory()) {
				walk(abs);
				continue;
			}
			const rel = relative(HARNESS, abs).split('\\').join('/');
			const dest = join(TARGET, VENDOR, rel);
			mkdirSync(dirname(dest), { recursive: true });
			writeFileSync(dest, readFileSync(abs, 'utf8'), 'utf8');
			count += 1;
		}
	};
	walk(src);
	log(`vendored ${name}/ (${count} files)`);
	return true;
}

// ── Per-agent projections ────────────────────────────────────────────────────

/** Codex reads AGENTS.md natively — it is the canonical projection the others derive from. */
function projectCodex(core) {
	write('AGENTS.md', generatedHeader('node build/project.mjs') + core);
}

/** Claude Code reads both AGENTS.md and CLAUDE.md: a one-line pointer costs nothing. */
function projectClaude() {
	write('CLAUDE.md', 'AGENTS.md\n');
}

/** Cursor wants one .mdc per rule, with its own frontmatter. */
function projectCursor(core) {
	write(
		'.cursor/rules/roymasoft-core.mdc',
		['---', 'description: roymasoft-ai core behavior contract', 'alwaysApply: true', '---', '', core].join('\n'),
	);

	for (const [file, description] of Object.entries(BEHAVIOR_RULES)) {
		const src = join(HARNESS, 'behavior', file);
		if (!existsSync(src)) continue;
		const name = file.replace(/\.md$/, '');
		write(
			`.cursor/rules/roymasoft-${name}.mdc`,
			['---', `description: ${description}`, 'alwaysApply: false', '---', '', readFileSync(src, 'utf8')].join('\n'),
		);
	}
}

/** Copilot: replace only our marked block, keep whatever else the repo put there. */
function projectCopilot(core) {
	const rel = '.github/copilot-instructions.md';
	const abs = join(TARGET, rel);
	const block = [BLOCK_START, generatedHeader('node build/project.mjs') + core, BLOCK_END].join('\n');

	if (existsSync(abs)) {
		const current = readFileSync(abs, 'utf8');
		if (current.includes(BLOCK_START) && current.includes(BLOCK_END)) {
			const before = current.slice(0, current.indexOf(BLOCK_START));
			const after = current.slice(current.indexOf(BLOCK_END) + BLOCK_END.length);
			write(rel, before + block + after);
			return;
		}
		write(rel, `${current.trimEnd()}\n\n${block}\n`);
		return;
	}
	write(rel, `${block}\n`);
}

function projectAntigravity(core) {
	write('.gemini/GEMINI.md', generatedHeader('node build/project.mjs') + core);
}

// ── Main ─────────────────────────────────────────────────────────────────────

function main() {
	if (TARGET === HARNESS) {
		console.error('error: run this against a target repository, not the harness itself.');
		console.error(`usage: node build/project.mjs <target-repo>`);
		process.exit(1);
	}
	if (!existsSync(TARGET)) {
		console.error(`error: target does not exist: ${TARGET}`);
		process.exit(1);
	}

	console.log(`roymasoft-ai -> ${TARGET}\n`);

	const core = rewritePointers(read('behavior/_core.md'));

	projectCodex(core);
	projectClaude();
	projectCursor(core);
	projectCopilot(core);
	projectAntigravity(core);

	console.log('');
	for (const dir of ['behavior', 'contracts', 'agents', 'skills']) vendorDir(dir);

	console.log(`\ndone. Restart your agent to pick up the new configuration.`);
}

main();
