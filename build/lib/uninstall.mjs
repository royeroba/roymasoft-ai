/**
 * Uninstall planning and execution.
 *
 * The hard part is not deleting — it is **not deleting what is not ours**. A client repository's
 * `.claude/skills/` may hold the human's own skills next to the projected ones, and
 * `.github/copilot-instructions.md` may carry their rules around our block.
 *
 * So every candidate is proved to be ours before it is touched:
 *   - full-file projections (AGENTS.md, GEMINI.md, Copilot) are edited to drop only our block,
 *     never deleted outright, unless nothing else remains in them
 *   - subagents and skills must both match a name this harness ships AND carry the marker we
 *     stamp on write — matching the name alone is not proof, a client repo can have its own
 *     skill or subagent that happens to share a name with one of ours
 *
 * Anything that fails the proof is left alone and reported. Planning is pure: `plan()` reads and
 * decides, `execute()` is the only function that writes.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync, rmSync, rmdirSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const VENDOR = '.rai';
const BLOCK_START = '<!-- roymasoft-ai:start -->';
const BLOCK_END = '<!-- roymasoft-ai:end -->';
const GENERATED_MARK = 'Generated by roymasoft-ai';
/** Same marker `project.mjs`'s `writeOwned` stamps on every skill/subagent file it writes — the
 *  proof that a same-named file is ours, not a client's own skill or subagent that predates us. */
const SKILL_MARK = '<!-- roymasoft-ai -->';

/** Full-file projections whose content may live inside block markers (current format, so a
 *  pre-existing file with the same name is never silently lost) or, from a run before that
 *  format existed, be the whole file (old format, proved by the generated header alone). */
const BLOCK_FILES = ['AGENTS.md', '.gemini/GEMINI.md', '.github/copilot-instructions.md'];

/** Directories that exist only because of the projection. */
const OWNED_DIRS = [VENDOR, '.codex/skills', '.antigravity/skills'];

/** Directories shared with the human: skills/agents are proved by the `SKILL_MARK` stamp (see
 *  above); hooks cannot carry a marker (no comment syntax in `.mjs`/`.json`), so name is the only
 *  proof available for them. */
const SHARED_DIRS = [
	{ dir: '.claude/agents', kind: 'agent' },
	{ dir: '.claude/skills', kind: 'skill' },
	{ dir: '.claude/hooks', kind: 'hook' },
	{ dir: '.codex/skills', kind: 'skill' },
	{ dir: '.antigravity/skills', kind: 'skill' },
];

function readIf(path) {
	try {
		return existsSync(path) ? readFileSync(path, 'utf8') : null;
	} catch {
		return null;
	}
}

function listDirs(abs) {
	if (!existsSync(abs)) return [];
	return readdirSync(abs).filter((e) => statSync(join(abs, e)).isDirectory());
}

function listFiles(abs) {
	if (!existsSync(abs)) return [];
	return readdirSync(abs).filter((e) => statSync(join(abs, e)).isFile());
}

/** What this harness ships, so the plan only ever names things it created. */
export function harnessInventory(harness) {
	return {
		skills: listDirs(join(harness, 'skills')).filter((n) => !n.startsWith('_')),
		agents: listFiles(join(harness, 'agents'))
			.filter((f) => f.endsWith('.md') && !f.startsWith('_'))
			.map((f) => f.replace(/\.md$/, '')),
		hooks: listFiles(join(harness, 'hooks')),
	};
}

/**
 * Computes what would be removed from `target`. Reads only.
 *
 * Returns `remove` (safe to delete), `edit` (files to rewrite without our block),
 * `keep` (deliberately left, with the reason) and `foreign` (looked like ours but failed the proof).
 */
export function plan(target, harness) {
	// The harness is the source, never a target. Uninstalling removes the harness *from* a
	// project; deleting the harness itself is `rm -rf` on the clone, and the human's call.
	if (resolve(target) === resolve(harness)) {
		throw new Error('refusing to uninstall from the harness itself — this removes it FROM a project, not the clone');
	}

	const inventory = harnessInventory(harness);
	const remove = [];
	const edit = [];
	const keep = [];
	const foreign = [];

	// AGENTS.md / GEMINI.md / Copilot: our content may live inside block markers (current format,
	// so a pre-existing file with the same name is never silently lost) or be the whole file, from
	// a run before that format existed (old format, proved by the generated header alone).
	for (const rel of BLOCK_FILES) {
		const text = readIf(join(target, rel));
		if (text === null) continue;
		if (text.includes(BLOCK_START) && text.includes(BLOCK_END)) {
			const before = text.slice(0, text.indexOf(BLOCK_START));
			const after = text.slice(text.indexOf(BLOCK_END) + BLOCK_END.length);
			const rest = `${before}${after}`.trim();
			if (rest) edit.push({ path: rel, content: `${rest}\n`, reason: 'keeps your content, drops our block' });
			else remove.push({ path: rel, kind: 'file' });
		} else if (text.includes(GENERATED_MARK)) {
			remove.push({ path: rel, kind: 'file' });
		} else {
			foreign.push({ path: rel, reason: 'edited by hand, or predates the harness — the generated marker is gone' });
		}
	}

	// CLAUDE.md: either exactly our one-line pointer (the common case), or our pointer wrapped in
	// block markers ahead of content the client already had before we ever wrote to this file.
	{
		const text = readIf(join(target, 'CLAUDE.md'));
		if (text !== null) {
			// `AGENTS.md` (no `@`) was the pointer before the `@`-import fix; `@AGENTS.md` is current.
			if (text.trim() === 'AGENTS.md' || text.trim() === '@AGENTS.md') {
				remove.push({ path: 'CLAUDE.md', kind: 'file' });
			} else if (text.includes(BLOCK_START) && text.includes(BLOCK_END)) {
				const before = text.slice(0, text.indexOf(BLOCK_START));
				const after = text.slice(text.indexOf(BLOCK_END) + BLOCK_END.length);
				const rest = `${before}${after}`.trim();
				if (rest) edit.push({ path: 'CLAUDE.md', content: `${rest}\n`, reason: 'keeps your content, drops our pointer block' });
				else remove.push({ path: 'CLAUDE.md', kind: 'file' });
			} else {
				foreign.push({ path: 'CLAUDE.md', reason: 'edited by hand — not our pointer' });
			}
		}
	}

	for (const dir of OWNED_DIRS) {
		if (existsSync(join(target, dir))) remove.push({ path: dir, kind: 'dir' });
	}

	// Cursor rules carry our prefix, which is proof enough.
	const cursorRules = join(target, '.cursor/rules');
	for (const file of listFiles(cursorRules)) {
		if (file.startsWith('rai-')) remove.push({ path: `.cursor/rules/${file}`, kind: 'file' });
	}

	for (const { dir, kind } of SHARED_DIRS) {
		const abs = join(target, dir);
		if (!existsSync(abs)) continue;

		if (kind === 'skill') {
			for (const name of listDirs(abs)) {
				const identity = readIf(join(abs, name, 'SKILL.md'));
				const owned = inventory.skills.includes(name) && identity !== null && identity.includes(SKILL_MARK);
				if (owned) remove.push({ path: `${dir}/${name}`, kind: 'dir' });
				else keep.push({ path: `${dir}/${name}`, reason: 'not ours — no roymasoft-ai marker' });
			}
		} else if (kind === 'agent') {
			for (const file of listFiles(abs)) {
				const text = readIf(join(abs, file));
				const owned = inventory.agents.includes(file.replace(/\.md$/, '')) && text !== null && text.includes(SKILL_MARK);
				if (owned) remove.push({ path: `${dir}/${file}`, kind: 'file' });
				else keep.push({ path: `${dir}/${file}`, reason: 'not ours — no roymasoft-ai marker' });
			}
		} else {
			// Hooks cannot carry a marker (no comment syntax in .mjs/.json) — name is the only proof.
			for (const file of listFiles(abs)) {
				if (inventory.hooks.includes(file)) remove.push({ path: `${dir}/${file}`, kind: 'file' });
				else keep.push({ path: `${dir}/${file}`, reason: `not a roymasoft-ai ${kind}` });
			}
		}
	}

	// PROJECT.md is the repository's own context, written for it. Never ours to delete.
	if (existsSync(join(target, 'PROJECT.md'))) {
		keep.push({ path: 'PROJECT.md', reason: 'your project context — delete it yourself if you want it gone' });
	}
	if (existsSync(join(target, 'specs'))) {
		keep.push({ path: 'specs/', reason: 'your specs, not harness files' });
	}

	return { target, remove, edit, keep, foreign };
}

/** Removes a directory that is now empty. Never recursive — an empty parent is the only target. */
function pruneEmpty(target, dir) {
	const abs = join(target, dir);
	try {
		if (existsSync(abs) && readdirSync(abs).length === 0) {
			rmdirSync(abs);
			return dir;
		}
	} catch {
		// A directory that will not go is not an error worth failing the uninstall over.
	}
	return null;
}

/** Applies a plan. The only function here that writes. */
export function execute(planned) {
	const done = [];
	const failed = [];

	for (const item of planned.remove) {
		const abs = join(planned.target, item.path);
		try {
			rmSync(abs, { recursive: item.kind === 'dir', force: true });
			done.push(item.path);
		} catch (err) {
			failed.push({ path: item.path, error: err.message });
		}
	}

	for (const item of planned.edit) {
		try {
			writeFileSync(join(planned.target, item.path), item.content, 'utf8');
			done.push(`${item.path} (edited)`);
		} catch (err) {
			failed.push({ path: item.path, error: err.message });
		}
	}

	// Parents we may have emptied. `.claude` and `.github` are only pruned when nothing else is in them.
	const pruned = [];
	for (const dir of ['.claude/agents', '.claude/skills', '.claude/hooks', '.codex/skills', '.antigravity/skills']) {
		const gone = pruneEmpty(planned.target, dir);
		if (gone) pruned.push(gone);
	}
	for (const dir of ['.claude', '.codex', '.antigravity', '.gemini', '.cursor/rules', '.cursor', '.github']) {
		const gone = pruneEmpty(planned.target, dir);
		if (gone) pruned.push(gone);
	}

	return { done, failed, pruned };
}

export { relative };
